"""Private disk attachments and selective, read-only MIME section retrieval."""
import hashlib
import imaplib
import os
import re
import secrets
import ssl
from contextlib import contextmanager
from pathlib import Path
from email import policy
from email.message import EmailMessage
from email.parser import BytesParser

from fastapi import HTTPException

MAX_BYTES = 10 * 1024 * 1024


def root():
    return Path(os.getenv('EDOCUMENTS_MAIL_ATTACHMENTS_DIR') or
                Path(__file__).resolve().parents[1] / 'data' / 'mail-attachments').resolve()


def disk_path(key):
    # Keys are generated by the server, never derived from sender filenames.
    if not re.fullmatch(r'[a-f0-9]{32}/[a-f0-9]{48}', key or ''):
        raise HTTPException(503, 'Niepoprawna lokalizacja załącznika.')
    target = (root() / key).resolve()
    if not target.is_relative_to(root()):
        raise HTTPException(503, 'Niepoprawna lokalizacja załącznika.')
    return target


def put(data, user_id):
    key = hashlib.sha256(user_id.encode()).hexdigest()[:32] + '/' + secrets.token_hex(24)
    target = disk_path(key)
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open('xb') as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
    except OSError:
        try: target.unlink(missing_ok=True)
        except OSError: pass
        raise HTTPException(503, 'Nie udało się zapisać załącznika na dysku serwera.') from None
    return key


def account_key(config):
    return hashlib.sha256(repr((config['host'].lower(), config['port'], config['username'], 'INBOX')).encode()).hexdigest()


def checked(result):
    status, data = result
    if status != 'OK': raise imaplib.IMAP4.error('IMAP command rejected')
    return data


@contextmanager
def connection(config, expected=None):
    client = None
    try:
        if config['security'] == 'ssl':
            client = imaplib.IMAP4_SSL(config['host'], config['port'], ssl_context=ssl.create_default_context(), timeout=15)
        else:
            client = imaplib.IMAP4(config['host'], config['port'], timeout=15)
            checked(client.starttls(ssl_context=ssl.create_default_context()))
        checked(client.login(config['username'], config['password']))
        checked(client.select('INBOX', readonly=True))
        _, validity = client.response('UIDVALIDITY')
        if not validity or not validity[0] or not validity[0].isdigit():
            raise imaplib.IMAP4.error('Missing UIDVALIDITY')
        if expected and (account_key(config) != expected['account'] or validity[0].decode() != expected['uid_validity']):
            raise HTTPException(409, 'Konto lub skrzynka IMAP uległy zmianie. Nie można pobrać oryginalnego załącznika.')
        yield client
    except (OSError, imaplib.IMAP4.error):
        raise HTTPException(502, 'Nie udało się pobrać danych z IMAP. Sprawdź połączenie i spróbuj ponownie.') from None
    finally:
        if client:
            try: client.logout()
            except (OSError, imaplib.IMAP4.error): pass


def literal(client, uid, section):
    if not re.fullmatch(r'(HEADER|[1-9][0-9]*(?:\.[1-9][0-9]*)*(?:\.MIME)?)', section):
        raise ValueError('Invalid MIME section')
    data = checked(client.uid('fetch', uid, f'(BODY.PEEK[{section}]<0.{MAX_BYTES + 1}>)'))
    payload = next((item[1] for item in data if isinstance(item, tuple) and isinstance(item[1], bytes)), None)
    if payload is None:
        raise HTTPException(410, 'Oryginalna wiadomość lub załącznik nie są już dostępne na serwerze pocztowym.')
    if len(payload) > MAX_BYTES: raise ValueError('MIME section too large')
    return payload


def structure(data):
    """Parse RFC 3501 lists, including quoted strings and IMAP literals."""
    wire = b''.join(item[0] + b'\r\n' + item[1] if isinstance(item, tuple) else item
                    for item in data if isinstance(item, (bytes, tuple)))
    match = re.search(rb'\bBODYSTRUCTURE\s+\(', wire, re.I)
    if not match: raise ValueError('Missing BODYSTRUCTURE')
    position = match.end() - 1

    def value(depth=0):
        nonlocal position
        if depth > 30: raise ValueError('MIME nesting too deep')
        while position < len(wire) and wire[position:position + 1].isspace(): position += 1
        if position >= len(wire): raise ValueError('Truncated structure')
        char = wire[position]; position += 1
        if char == 40:
            result = []
            while True:
                while position < len(wire) and wire[position:position + 1].isspace(): position += 1
                if position >= len(wire): raise ValueError('Truncated structure')
                if wire[position] == 41: position += 1; return result
                result.append(value(depth + 1))
        if char == 34:
            result = bytearray()
            while position < len(wire):
                char = wire[position]; position += 1
                if char == 34: return result.decode('utf-8', errors='replace')
                if char == 92:
                    if position >= len(wire): break
                    char = wire[position]; position += 1
                result.append(char)
            raise ValueError('Truncated string')
        if char == 123:
            end = wire.find(b'}\r\n', position)
            if end < 0: raise ValueError('Invalid literal')
            length = int(wire[position:end]); position = end + 3
            result = wire[position:position + length]; position += length
            if len(result) != length: raise ValueError('Truncated literal')
            return result.decode('utf-8', errors='replace')
        start = position - 1
        while position < len(wire) and wire[position] not in b' ()\r\n': position += 1
        token = wire[start:position].decode('ascii')
        return None if token.upper() == 'NIL' else token

    return value()


def leaves(node, prefix=''):
    if not isinstance(node, list) or not node: raise ValueError('Invalid MIME structure')
    if isinstance(node[0], list):
        children = next((i for i, item in enumerate(node) if not isinstance(item, list)), len(node))
        disposition = node[children + 2] if len(node) > children + 2 else None
        if isinstance(disposition, list) and disposition and str(disposition[0]).upper() == 'ATTACHMENT':
            yield prefix or '1', node
            return
        for index, child in enumerate(node):
            if not isinstance(child, list): break
            yield from leaves(child, f'{prefix}.{index + 1}' if prefix else str(index + 1))
    else:
        if len(node) < 7: raise ValueError('Invalid MIME part')
        # MESSAGE/RFC822 is kept whole as an attachment, never traversed as text.
        yield prefix or '1', node


def encoded_size(node):
    if isinstance(node[0], list):
        children = []
        for child in node:
            if not isinstance(child, list): break
            children.append(child)
        return sum(encoded_size(child) for child in children)
    return int(node[6])


def read_message(client, uid, parse_message):
    tree = structure(checked(client.uid('fetch', uid, '(BODYSTRUCTURE)')))
    original = BytesParser(policy=policy.default).parsebytes(literal(client, uid, 'HEADER'))
    message = EmailMessage()
    for name in ('From', 'To', 'Subject', 'Date'):
        if original.get(name): message[name] = str(original[name])
    message.make_mixed()
    attachments = []
    body_parts = 0
    for section, node in leaves(tree):
        mime = BytesParser(policy=policy.default).parsebytes(literal(client, uid, section + '.MIME'))
        is_file = mime.get_filename() or mime.get_content_disposition() == 'attachment' or str(node[0]).upper() != 'TEXT'
        if is_file:
            name = (mime.get_filename() or 'załącznik').replace('\\', '/').split('/')[-1]
            name = ''.join(c for c in name if ord(c) >= 32 and ord(c) != 127)[:200] or 'załącznik'
            attachments.append((name, encoded_size(node), section))
            if len(attachments) > 50: raise ValueError('Too many attachments')
        elif str(node[1]).upper() in ('PLAIN', 'HTML'):
            body_parts += 1
            if body_parts > 50: raise ValueError('Too many text parts')
            body = literal(client, uid, section)
            message.attach(BytesParser(policy=policy.default).parsebytes(mime.as_bytes() + body))
    parsed = parse_message(message.as_bytes())
    parsed['remote_attachments'] = attachments
    return parsed


def fetch(config, source, section):
    if not source['uid'].isdigit(): raise HTTPException(409, 'Niepoprawny identyfikator IMAP.')
    try:
        with connection(config, source) as client:
            mime = literal(client, source['uid'].encode(), section + '.MIME')
            payload = literal(client, source['uid'].encode(), section)
            part = BytesParser(policy=policy.default).parsebytes(mime + payload)
            data = part.get_payload(decode=True)
            if data is None and (part.get_content_type() == 'message/rfc822' or part.is_multipart()):
                data = payload
            if data is None or len(data) > MAX_BYTES: raise ValueError('Invalid attachment')
            return data
    except (ValueError, LookupError, UnicodeError):
        raise HTTPException(422, 'Nie udało się odczytać załącznika (limit 10 MB).') from None
